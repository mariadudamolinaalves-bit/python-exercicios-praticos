# Desafio 2: Situação de Alunos
# Menor que 5: “Reprovado”.
# De 5 até menos de 7: “Recuperação”.
# De 7 até 10: “Aprovado”.
nota = float(input("digite sua nota:"))
if nota < 5 :
    print("Reprovado")
elif nota <= 7:
    print("Recuperação")
else:
    print("Aprovado")






